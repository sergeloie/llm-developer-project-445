"""Редактор: собирает финальный ответ абоненту из докладов агентов.

Единственный агент, чей текст уходит пользователю.
"""
from __future__ import annotations

from app import llm

EDITOR_PROMPT = """Ты редактор чата мобильного оператора. Пишешь абоненту краткий ответ
по-русски (2–5 предложений), только на основе докладов агентов. Ничего не выдумывай:
не придумывай суммы, даты, тарифы и правила, которых нет в докладах. Если агент базы знаний
привёл источник, обязательно напиши «источник: <source>» в конце соответствующего утверждения.
Если есть только факты данных, ответь только на них. Если докладов нет — вежливо скажи,
что не смог найти данные, и предложи уточнить вопрос. Не раскрывай внутренние имена агентов
и не обсуждай план."""

# Живую карточку показывает код событием SSE, и редактор в этом ходу не
# вызывается: пересказывать карточку текстом ему не приходится.


def build_editor(session=None):
    """Агент без инструментов: редактирует текст, а не собирает данные."""
    return llm.build_agent("editor", EDITOR_PROMPT)


def editor_task(message: str, runs: list[dict]) -> str:
    """Сообщение абонента + нумерованные доклады агентов + источники."""
    blocks = []
    for index, run in enumerate(runs, 1):
        block = f"{index}. Доклад агента {run.get('agent', '?')}: {run.get('report', '')}".strip()
        sources = run.get("sources") or []
        if sources:
            block += f"\n   Источники из базы знаний: {', '.join(sources)}"
        blocks.append(block)

    reports = "\n".join(blocks) if blocks else "(докладов нет)"
    return (
        f"Вопрос абонента: {message}\n\n"
        f"Доклады агентов:\n{reports}\n\n"
        "Напиши абоненту краткий ответ строго по докладам. Если использовал базу знаний, "
        "обязательно укажи источник в формате «источник: <source>»."
    )
